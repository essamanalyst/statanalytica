// نوع للحصول على جميع مفاتيح الترجمة
type DeepKeys<T, P extends string = ''> = T extends object
  ? {
      [K in keyof T]: K extends string
        ? T[K] extends { ar: string; en: string }
          ? `${P}${K}`
          : DeepKeys<T[K], `${P}${K}.`>
        : never;
    }[keyof T]
  : never;

export type TranslationKey = DeepKeys<typeof translations>;

// دالة للحصول على الترجمة
export function getTranslation(key: string, language: Language): string {
  const keys = key.split('.');
  let result: any = translations;
  
  for (const k of keys) {
    if (result && typeof result === 'object' && k in result) {
      result = result[k];
    } else {
      console.warn(`Translation key not found: ${key}`);
      return key;
    }
  }
  
  if (result && typeof result === 'object' && language in result) {
    return result[language];
  }
  
  console.warn(`Translation not found for key: ${key}, language: ${language}`);
  return key;
}

// دالة للحصول على الترجمة مع متغيرات
export function getTranslationWithVars(
  key: string,
  language: Language,
  vars: Record<string, string | number>
): string {
  let translation = getTranslation(key, language);
  
  for (const [varKey, varValue] of Object.entries(vars)) {
    translation = translation.replace(new RegExp(`\\{${varKey}\\}`, 'g'), String(varValue));
  }
  
  return translation;
}
